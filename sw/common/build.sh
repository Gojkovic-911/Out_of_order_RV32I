#!/bin/bash
# Build a C program (directory of .c files or one .c file) for one memory map
# Usage: build.sh <src> <out dir> [<platform>.mk] [--host]
#   no <platform>.mk: CPU testbench map, DMEM 0..2^WADDR, no peripherals
#   --host: expected.txt from a host run of the same code
set -e

SRC=$1
OUT=$2
PLATFORM_MK=$3
HOST=$4
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
COMMON="$ROOT/sw/common"
CROSS=${CFG_CROSS:-riscv64-unknown-elf}
CFLAGS=${CFG_CFLAGS:--O2}

if [ -d "$SRC" ]; then
    APP=$(basename "$SRC")
    SRCS=$(ls "$SRC"/*.c)
else
    APP=$(basename "$SRC" .c)
    SRCS=$SRC
fi

# Memory sizes: IMEM from cpu.mk, DMEM from the platform
mk_value() {
    sed -n -E "s/^\s*$1\s*=\s*(\S+)\s*$/\1/p" "$2" | head -1
}
WADDR=$(mk_value WADDR "${CONFIG_MK:-$ROOT/RV32I/cpu.mk}")
IMEM_SIZE=$((1 << WADDR))
if [ -n "$PLATFORM_MK" ]; then
    DMEM_BASE=$(mk_value DMEM_BASE "$PLATFORM_MK")
    DMEM_SIZE=$(mk_value DMEM_SIZE "$PLATFORM_MK")
else
    DMEM_BASE=0x00000000
    DMEM_SIZE=$IMEM_SIZE
fi

mkdir -p "$OUT"

# Memory map and peripheral addresses
cat > "$OUT/memory.ld" <<MAP
MEMORY
{
    IMEM (rx) : ORIGIN = 0,            LENGTH = $IMEM_SIZE
    DMEM (rw) : ORIGIN = $DMEM_BASE, LENGTH = $DMEM_SIZE
}
MAP
{
    echo "/* Generated by build.sh */"
    echo "#define DMEM_BASE $DMEM_BASE"
    if [ -n "$PLATFORM_MK" ]; then
        sed -n -E 's/^\s*(\w+_(BASE|MHZ))\s*=\s*(\S+)\s*$/#define \1 \3/p' "$PLATFORM_MK" | grep -v ' DMEM_BASE '
    fi
} > "$OUT/platform.h"

# Compile and link
$CROSS-gcc -march=rv32i -mabi=ilp32 $CFLAGS -ffreestanding -nostdlib -I"$OUT" \
    -T "$COMMON/link.ld" -L "$OUT" -Wl,--no-check-sections,-Map,"$OUT/$APP.map" \
    "$COMMON/crt0.S" $SRCS -lgcc -o "$OUT/$APP.elf"
$CROSS-objdump -d "$OUT/$APP.elf" > "$OUT/$APP.dis"
# Code and data apart for updatemem (DMEM overlaps IMEM addresses)
$CROSS-objcopy -j .text "$OUT/$APP.elf" "$OUT/${APP}_imem.elf"
$CROSS-objcopy -j .rodata -j .data "$OUT/$APP.elf" "$OUT/${APP}_dmem.elf"

# Words for the memories, one 32-bit binary word per line
to_words() {
    truncate -s %4 "$1"
    od -An -v -t x4 -w4 "$1" | perl -ne 's/\s//g; printf "%032b\n", hex($_) if length' > "$2"
    rm -f "$1"
}
$CROSS-objcopy -O binary -j .text "$OUT/$APP.elf" "$OUT/imem.raw"
to_words "$OUT/imem.raw" "$OUT/instr_mem.txt"
$CROSS-objcopy -O binary -j .rodata -j .data "$OUT/$APP.elf" "$OUT/dmem.raw"
to_words "$OUT/dmem.raw" "$OUT/data_mem.txt"

# Expected result from a host run
if [ "$HOST" = "--host" ]; then
    gcc -O2 -I"$OUT" -Dmain=app_main -c $SRCS -o "$OUT/host_app.o"
    gcc -O2 "$COMMON/host_main.c" "$OUT/host_app.o" -o "$OUT/host_$APP"
    "$OUT/host_$APP" > "$OUT/expected.txt"
    rm -f "$OUT/host_app.o"
fi

echo "Built $APP: $(wc -l < "$OUT/instr_mem.txt") code words, $(wc -l < "$OUT/data_mem.txt") data words"
